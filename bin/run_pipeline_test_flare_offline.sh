#!/usr/bin/env bash
set -euo pipefail

# ═════════════════════════════════════════════════════════════════════════════
#  FLARE offline runner — derived from run_test_offline.sh
#
#  Adds the SAILOR → FLARE path (RBP-STAMP / RBFOX2-BAMR test data built by
#  bin/make_test_dataset_flare.sh). The base MARINE offline runner already
#  overrode FASTP / SAMTOOLS_FAIDX / STAR_ALIGN / FEATURECOUNTS /
#  INFER_STRANDEDNESS / FASTQC / MULTIQC. The FLARE path reuses those upstream
#  steps and ADDS new containerized processes (SAILOR edit-calling, FLARE
#  clustering, and any tabix/bedtools helpers) whose Wave/Seqera images the HPC
#  egress proxy will 403 the same way.
#
#  >>> TEMPLATE STATUS <<<
#  The FLARE process names and image filenames below are PLACEHOLDERS marked
#  with  # FIXME(flare) . Run once, read the .command.run / trace to get the
#  real process names and the Wave image URLs, pre-pull them via Lima, then
#  fill in the three FIXME regions (REQUIRED_IMAGES, the process{} overrides,
#  and — if needed — the pre-pull note).
# ═════════════════════════════════════════════════════════════════════════════

# ── Profiles to run — comment out any you want to skip ───────────────────────
# NOTE: FLARE test profiles, NOT the MARINE ones. These match the companion
# configs conf/test_bulk_bam_flare.config / conf/test_bulk_fastq_flare.config.
PROFILES=(
    test_bulk_bam_flare
    test_bulk_fastq_flare
)

# ── Environment ───────────────────────────────────────────────────────────────
export NXF_HOME=/vast/users/mohamad.kassab/luiz/nf-stamp/nf-core-ribostamp-dev/.nextflow
export NXF_OFFLINE=true      # NOTE: stops Nextflow's own network calls only —
                             # does NOT stop Singularity image pulls. Images must
                             # already exist in the cache (see PRE-PULL section).

export NXF_SINGULARITY_CACHEDIR=/vast/users/mohamad.kassab/luiz/nf-stamp/singularity_cache
mkdir -p "$NXF_SINGULARITY_CACHEDIR"

PIPELINE_DIR="/vast/users/mohamad.kassab/luiz/nf-stamp/nf-core-ribostamp-dev"
export OUTPUT_DIR=/vast/users/mohamad.kassab/luiz/nf-stamp/nfcore-ribostamp-run
mkdir -p "$OUTPUT_DIR"

# ── System-specific paths — edit these for your cluster ──────────────────────
# snakemake 8.x env (SAILOR needs 8.x: it uses --use-singularity/--singularity-*,
# removed in snakemake 9). Absolute path so SAILOR execs it regardless of the
# active conda env. FLARE clusters the C>T edits SAILOR calls, so this path is
# still required for the flare path.
SNAKEMAKE_PATH="/vast/users/mohamad.kassab/miniconda3/envs/snakemake8/bin/snakemake"

# Internal bin dir used by Wave "pixi" container builds. When an image is the
# docker/pixi flavor, the tool lives here and is normally put on PATH by the
# container entrypoint — which Nextflow's `apptainer exec` bypasses, causing
# "command not found" (exit 127). Prepending this to PATH inside the container
# fixes that. Harmless when a candidate dir is absent (nonexistent PATH entries
# are simply skipped). Wave images vary by build toolchain:
#   * pixi builds  -> tool in /opt/wave/.pixi/envs/default/bin   (e.g. FASTQC 0.12.1)
#   * conda builds -> tool in /opt/conda/bin                     (e.g. MULTIQC 1.34)
# Include BOTH so the same override covers either flavor; standard system dirs
# are appended so oras-flavored images (tool already on default PATH) also work.
WAVE_PIXI_BIN="/opt/wave/.pixi/envs/default/bin"
WAVE_CONDA_BIN="/opt/conda/bin"
CONTAINER_PATH="${WAVE_PIXI_BIN}:${WAVE_CONDA_BIN}:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"

# ── Offline config ───────────────────────────────────────────────────────────
# Regenerated on every run so this script stays the single source of truth.
#   1. report/timeline/trace/dag overwrite flags (avoid FileAlreadyExistsException on reruns)
#   2. param defaults to silence "Access to undefined parameter" warnings
#   3. container overrides binding every Wave/Seqera-blocked process to a local .img
#      — the base MARINE-path processes PLUS the new SAILOR/FLARE processes
#   4. containerOptions injecting the tool bin onto PATH, uniformly, for ALL
#      overridden processes — deterministic regardless of image build flavor
OFFLINE_CONFIG="$(dirname "$0")/offline_flare.config"
cat > "$OFFLINE_CONFIG" <<EOF
// AUTO-GENERATED by $(basename "$0") — do not edit by hand.

// ── Prevent FileAlreadyExistsException on re-runs into the same --outdir ──
report.overwrite   = true
timeline.overwrite = true
trace.overwrite    = true
dag.overwrite      = true

// ── Silence "Access to undefined parameter" warnings ──
params.marine_sif          = params.containsKey('marine_sif')          ? params.marine_sif          : null
params.ribostamp_utils_sif = params.containsKey('ribostamp_utils_sif') ? params.ribostamp_utils_sif : null

// ── Container overrides: bind every Wave/Seqera-blocked process to a local .img ──
// The HPC egress proxy 403s community.wave.seqera.io / community-cr-prod.seqera.io.
// When a container directive is an existing file path, Apptainer uses it directly
// and never contacts the registry. Passed via -c LAST so it wins over any
// arch-split containers_singularity_* / containers_docker_* config the pipeline includes.
params.sing_cache     = '${NXF_SINGULARITY_CACHEDIR}'
params.container_path = '${CONTAINER_PATH}'

process {
    // ── Upstream MARINE-path processes (unchanged from base offline runner) ──
    withName: 'FASTP' {
        container        = "\${params.sing_cache}/community.wave.seqera.io-library-fastp-1.3.4--b75b637bf1c0f4b1.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'SAMTOOLS_FAIDX' {
        container        = "\${params.sing_cache}/community.wave.seqera.io-library-samtools_star-3d56ec4ef8fcee61.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'STAR_ALIGN' {
        container        = "\${params.sing_cache}/community.wave.seqera.io-library-samtools_star-3d56ec4ef8fcee61.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'FEATURECOUNTS' {
        container        = "\${params.sing_cache}/subread-2.1.1.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'INFER_STRANDEDNESS' {
        container        = "\${params.sing_cache}/rseqc-5.0.4.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'FASTQC' {
        container        = "\${params.sing_cache}/fastqc-0.12.1.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }
    withName: 'MULTIQC' {
        container        = "\${params.sing_cache}/multiqc-1.34.img"
        containerOptions = "--env PATH=\${params.container_path}"
    }

    // ══════════════════════════════════════════════════════════════════════
    //  FIXME(flare): SAILOR / FLARE processes — PLACEHOLDERS
    //  ---------------------------------------------------------------------
    //  After the first flare run, get the real process names + image URLs:
    //
    //    # process names actually executed (adjust outdir):
    //    grep -hoP 'process > \K[^ ]+' \\
    //      ${OUTPUT_DIR}/results_off_test_bulk_bam_flare/pipeline_info/execution_trace*.txt \\
    //      2>/dev/null | sort -u
    //    # OR from the trace TSV column 'name':
    //    awk -F'\\t' 'NR>1{print \$4}' \\
    //      ${OUTPUT_DIR}/results_off_test_bulk_bam_flare/pipeline_info/execution_trace*.txt \\
    //      | sed 's/ .*//' | sort -u
    //
    //    # the Wave/Seqera container each blocked task tried to pull
    //    # (look in the failing task's .command.run for 'community.wave.seqera.io'):
    //    grep -RhoP 'community[.-]wave\\.seqera\\.io[^"'\\'' ]+' \\
    //      ${OUTPUT_DIR}/results_off_test_bulk_bam_flare/../work 2>/dev/null | sort -u
    //
    //  Then pre-pull each (see PRE-PULL section) and replace the names/files
    //  below. Uncomment blocks as you confirm them. Typical FLARE-path steps:
    //  SAILOR (ct-edit calling), FLARE (edit clustering), plus tabix/bedtools
    //  or bcftools helpers. Adjust to whatever the trace shows.
    //
    //  withName: 'SAILOR' {                                    // FIXME(flare)
    //      container        = "\${params.sing_cache}/FIXME-sailor.img"
    //      containerOptions = "--env PATH=\${params.container_path}"
    //  }
    //  withName: 'FLARE' {                                     // FIXME(flare)
    //      container        = "\${params.sing_cache}/FIXME-flare.img"
    //      containerOptions = "--env PATH=\${params.container_path}"
    //  }
    //  withName: 'TABIX' {                                     // FIXME(flare)
    //      container        = "\${params.sing_cache}/FIXME-tabix.img"
    //      containerOptions = "--env PATH=\${params.container_path}"
    //  }
    //  withName: 'BEDTOOLS.*' {                                // FIXME(flare)  (regex ok)
    //      container        = "\${params.sing_cache}/FIXME-bedtools.img"
    //      containerOptions = "--env PATH=\${params.container_path}"
    //  }
    // ══════════════════════════════════════════════════════════════════════
}
EOF
echo "Wrote $OFFLINE_CONFIG"

# ── PRE-PULL: Seqera Wave images blocked by the HPC egress proxy (HTTP 403) ───
# Pull ONCE from a host with open egress (Lima on your Mac), amd64, then scp into
# $NXF_SINGULARITY_CACHEDIR. Prefer the ORAS variant for Apptainer where possible
# (tool on default PATH); the pixi/docker variant needs the PATH fix above.
#
#   apptainer pull --arch amd64 <name>.img docker://community.wave.seqera.io/library/<ref>
#
# Guard: refuse to launch if any required image is missing.
REQUIRED_IMAGES=(
    # ── Upstream MARINE-path images (shared with base runner) ──
    "community.wave.seqera.io-library-fastp-1.3.4--b75b637bf1c0f4b1.img"
    "community.wave.seqera.io-library-samtools_star-3d56ec4ef8fcee61.img"
    "fastqc-0.12.1.img"
    "multiqc-1.34.img"
    "subread-2.1.1.img"
    "rseqc-5.0.4.img"
    # ── FIXME(flare): add SAILOR/FLARE image filenames once known ──
    # "FIXME-sailor.img"
    # "FIXME-flare.img"
    # "FIXME-tabix.img"
    # "FIXME-bedtools.img"
)
missing=0
for img in "${REQUIRED_IMAGES[@]}"; do
    if [[ ! -e "$NXF_SINGULARITY_CACHEDIR/$img" ]]; then
        echo "MISSING cached image: $img"
        missing=1
    fi
done
if [[ "$missing" -eq 1 ]]; then
    echo ""
    echo "One or more blocked images are not in the cache. Pre-pull them from a"
    echo "connected host (Lima on your Mac), scp into \$NXF_SINGULARITY_CACHEDIR,"
    echo "then re-run this script."
    echo "To bypass this guard (e.g. you overrode containers to quay.io, or you're"
    echo "doing the first exploratory flare run to discover the SAILOR/FLARE images),"
    echo "set SKIP_IMAGE_CHECK=1 before running."
    [[ "${SKIP_IMAGE_CHECK:-0}" != "1" ]] && exit 1
fi
echo "All required container images present."

# ── Loop ─────────────────────────────────────────────────────────────────────
for PROFILE in "${PROFILES[@]}"; do
    echo "======================================================"
    echo "  ribostamp flare test: ${PROFILE}"
    echo "  started: $(date)"
    echo "======================================================"

    # -c "$OFFLINE_CONFIG" passed LAST so container overrides win.
    # NOTE: run this script FROM the same directory every time (your work/ lives
    # in scripts/); otherwise -resume won't find the cache.
    nextflow run "$PIPELINE_DIR/main.nf" \
        -profile "${PROFILE},singularity" \
        -c "$OFFLINE_CONFIG" \
        --outdir "${OUTPUT_DIR}/results_flare_off_${PROFILE}" \
        --sailor_snakemake_path "$SNAKEMAKE_PATH" \
        -resume
        # ADDED (optional): supply local .sif files to skip Docker Hub pulls:
        # --marine_sif "${NXF_SINGULARITY_CACHEDIR}/docker.io-aravindsundaravadivelu-marine-1.0.2.img" \
        # --ribostamp_utils_sif "${NXF_SINGULARITY_CACHEDIR}/docker.io-aravindsundaravadivelu-ribostamp_utils-1.0.0.img"

    echo "======================================================"
    echo "  ribostamp flare test: ${PROFILE} — DONE ($(date))"
    echo "======================================================"
    echo ""
done
